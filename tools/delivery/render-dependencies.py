#!/usr/bin/env python3
"""Render committed build definitions from one set of dependency pins."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]


def pins():
    values = {}
    for line in (ROOT / 'tools/delivery/dependencies.env').read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        if not re.fullmatch(r'[A-Z][A-Z0-9_]*=[a-zA-Z0-9/:.,_-]+', line):
            raise ValueError('invalid dependency manifest line')
        key, value = line.split('=', 1)
        if key in values:
            raise ValueError(f'duplicate pin: {key}')
        values[key] = value
    lock = ROOT / 'composer.lock'
    if lock.is_file():
        packages = [p for p in json.loads(lock.read_text())['packages']
                    if p['name'] == 'tecnickcom/tcpdf']
        if len(packages) != 1:
            raise ValueError('composer.lock must contain exactly one TCPDF package')
        package = packages[0]
        values.update(TCPDF_VERSION=package['version'], TCPDF_REVISION=package['source']['reference'])
        if not re.fullmatch(r'[0-9a-f]{40}', values['TCPDF_REVISION']):
            raise ValueError('invalid TCPDF source revision')
    if not values['PHP_IMAGE'].startswith('php:' + values['PHP_VERSION'] + '-'):
        raise ValueError('PHP image/runtime mismatch')
    if not values['PHP_FPM_IMAGE'].startswith('php:' + values['PHP_VERSION'] + '-fpm-'):
        raise ValueError('PHP FPM image/runtime mismatch')
    if not values['NODE_IMAGE'].startswith('node:' + values['NODE_VERSION'] + '-'):
        raise ValueError('Node image/runtime mismatch')
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--tcpdf', action='store_true')
    parser.add_argument('--env', action='store_true')
    args = parser.parse_args()
    values = pins()
    if args.env:
        for key, value in values.items():
            if not re.fullmatch(r'[A-Z][A-Z0-9_]*', key) or not re.fullmatch(r'[a-zA-Z0-9/:.,_-]+', value):
                raise ValueError(f'invalid export: {key}')
            print(f'{key}={value}')
        return 0
    if args.tcpdf:
        if 'TCPDF_VERSION' not in values:
            raise ValueError('composer.lock is required for TCPDF metadata')
        print(values['TCPDF_VERSION'], values['TCPDF_REVISION'])
        return 0
    targets = {'Dockerfile.pilot.in': 'Dockerfile',
               'Dockerfile.runtime.in': 'deploy/runtime/Dockerfile',
               'Dockerfile.test.in': 'tools/verification/Dockerfile.test',
               'compose.yaml.in': 'compose.yaml', 'compose.test.yaml.in': 'compose.test.yaml',
               'compose.runtime.yaml.in': 'deploy/runtime/compose.yaml'}
    for template, target in targets.items():
        if not (ROOT / target).exists() and not (ROOT / 'composer.lock').is_file():
            continue
        text = (ROOT / 'tools/delivery' / template).read_text()
        rendered = (text if template == 'compose.runtime.yaml.in' else
                    '# Generated by tools/delivery/render-dependencies.py; edit its template/pins.\n'
                    + re.sub(r'@([A-Z_]+)@', lambda m: values[m[1]], text))
        path = ROOT / target
        if args.check:
            if not path.is_file() or path.read_text() != rendered:
                raise ValueError(f'{target} drifted; run python3 tools/delivery/render-dependencies.py')
        else:
            path.write_text(rendered)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, KeyError, OSError) as error:
        print(f'SETUP_FAILURE: {error}', file=sys.stderr)
        sys.exit(1)
