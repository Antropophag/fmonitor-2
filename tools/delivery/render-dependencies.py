#!/usr/bin/env python3
"""Render committed build definitions from one set of dependency pins."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]


def pins():
    values = {}
    for line in (ROOT / 'tools/delivery/dependencies.env').read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        if not re.fullmatch(r'[A-Z_]+=[a-zA-Z0-9/:.,_-]+', line):
            raise ValueError('invalid dependency manifest line')
        key, value = line.split('=', 1)
        if key in values:
            raise ValueError(f'duplicate pin: {key}')
        values[key] = value
    packages = [p for p in json.loads((ROOT / 'composer.lock').read_text())['packages']
                if p['name'] == 'tecnickcom/tcpdf']
    if len(packages) != 1:
        raise ValueError('composer.lock must contain exactly one TCPDF package')
    package = packages[0]
    values.update(TCPDF_VERSION=package['version'], TCPDF_REVISION=package['source']['reference'])
    if not re.fullmatch(r'[0-9a-f]{40}', values['TCPDF_REVISION']):
        raise ValueError('invalid TCPDF source revision')
    if not values['PHP_IMAGE'].startswith('php:' + values['PHP_VERSION'] + '-'):
        raise ValueError('PHP image/runtime mismatch')
    if not values['NODE_IMAGE'].startswith('node:' + values['NODE_VERSION'] + '-'):
        raise ValueError('Node image/runtime mismatch')
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--tcpdf', action='store_true')
    args = parser.parse_args()
    values = pins()
    if args.tcpdf:
        print(values['TCPDF_VERSION'], values['TCPDF_REVISION'])
        return 0
    targets = {'Dockerfile.pilot.in': 'Dockerfile',
               'Dockerfile.test.in': 'tools/verification/Dockerfile.test',
               'compose.yaml.in': 'compose.yaml', 'compose.test.yaml.in': 'compose.test.yaml'}
    for template, target in targets.items():
        text = (ROOT / 'tools/delivery' / template).read_text()
        rendered = '# Generated by tools/delivery/render-dependencies.py; edit its template/pins.\n'
        rendered += re.sub(r'@([A-Z_]+)@', lambda m: values[m[1]], text)
        path = ROOT / target
        if args.check:
            if not path.is_file() or path.read_text() != rendered:
                raise ValueError(f'{target} drifted; run python3 tools/delivery/render-dependencies.py')
        else:
            path.write_text(rendered)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, KeyError, OSError) as error:
        print(f'SETUP_FAILURE: {error}', file=sys.stderr)
        sys.exit(1)
